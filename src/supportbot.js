const GREETING =
  'Здравствуйте! Я бот поддержки FinFlow. Опишите вопрос своими словами — отвечу по частым темам (тарифы, промокоды, почта, 2FA, счета, цели). Если нужен живой человек — нажмите «Позвать человека».';

function botReply(text) {
  const t = (text || '').toLowerCase();
  for (const it of INTENTS) {
    if (it.k.some((kw) => t.includes(kw))) {
      return { reply: it.a + '\n\nЕсли это не помогло — нажмите «Позвать человека».', matched: true };
    }
  }
  return {
    reply:
      'Не уверен, что понял вопрос. Опишите подробнее — или нажмите «Позвать человека», и вам ответит поддержка.',
    matched: false,
  };
}

