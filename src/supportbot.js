function botReply(text) {
  const t = (text || '').toLowerCase();
  for (const it of INTENTS) {
    if (it.k.some((kw) => t.includes(kw))) {
      return { reply: it.a + '\n\nПомогло? Если нет — жмите «Позвать человека», подключу поддержку.', matched: true };
    }
  }
  return {
    reply:
      'Хм, не совсем поняла вопрос. Опишите подробнее своими словами — или жмите «Позвать человека», и с вами свяжется поддержка.',
    matched: false,
  };
}

